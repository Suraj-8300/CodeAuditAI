"""
report_generator.py
--------------------
Generates executive-level Markdown and JSON audit reports for CodeAuditAI.
Provides structured summaries, vulnerability scorecards, Big-O tables,
and copy-pasteable remediations ready for team reviews and stakeholders.
"""

import os
import re
from typing import List, Dict, Any, Optional
from datetime import datetime


def _extract_rating(security_report: str) -> str:
    """Extracts [CRITICAL], [WARNING], or [SAFE] rating."""
    if "[CRITICAL]" in security_report:
        return "CRITICAL"
    elif "[WARNING]" in security_report:
        return "WARNING"
    elif "[SAFE]" in security_report:
        return "SAFE"
    return "UNKNOWN"


def generate_markdown_report(
    repo_name: str,
    repo_path: str,
    audited_files: List[Dict[str, Any]],
    repo_summary: str = "",
    include_remediations: bool = True
) -> str:
    """
    Builds a full-fledged Markdown audit report.
    """
    if not isinstance(audited_files, list):
        audited_files = []

    total_files = len(audited_files)
    critical_count = 0
    warning_count = 0
    safe_count = 0

    for f in audited_files:
        if not isinstance(f, dict):
            continue
        sec = str(f.get("security_report", "") or "")
        rating = _extract_rating(sec)
        if rating == "CRITICAL":
            critical_count += 1
        elif rating == "WARNING":
            warning_count += 1
        elif rating == "SAFE":
            safe_count += 1

    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Overall project status badge
    if critical_count > 0:
        overall_status = "🔴 HIGH RISK (Critical Flaws Detected)"
    elif warning_count > 0:
        overall_status = "🟡 MODERATE RISK (Warnings Require Review)"
    else:
        overall_status = "🟢 HEALTHY (No Major Vulnerabilities Identified)"

    # Defensive calculation of percentage values (CWE-393)
    crit_pct = (critical_count / total_files * 100.0) if total_files > 0 else 0.0
    warn_pct = (warning_count / total_files * 100.0) if total_files > 0 else 0.0
    safe_pct = (safe_count / total_files * 100.0) if total_files > 0 else 0.0

    lines = [
        f"# 🛡️ CodeAuditAI Comprehensive Security & Performance Report",
        f"",
        f"> **Generated:** {now_str} | **Engine:** CodeAuditAI Multi-Agent Consensus",
        f"",
        f"---",
        f"",
        f"## 📋 Executive Overview",
        f"",
        f"- **Target Repository:** `{repo_name}`",
        f"- **Location / Source:** `{repo_path}`",
        f"- **Audited Source Files:** `{total_files}`",
        f"- **Overall Risk Posture:** **{overall_status}**",
        f"",
        f"### 📊 Security Scorecard Summary",
        f"",
        f"| Severity Level | File Count | Percentage |",
        f"| :--- | :---: | :---: |",
        f"| 🔴 **CRITICAL** | {critical_count} | {crit_pct:.1f}% |",
        f"| 🟡 **WARNING** | {warning_count} | {warn_pct:.1f}% |",
        f"| 🟢 **SAFE** | {safe_count} | {safe_pct:.1f}% |",
        f"",
    ]

    if repo_summary:
        lines.extend([
            f"### 🗺️ Repository Architecture Summary",
            f"",
            f"{repo_summary}",
            f"",
        ])

    lines.extend([
        f"---",
        f"",
        f"## 📂 Detailed File Audit Breakdowns",
        f"",
    ])

    for i, file_info in enumerate(audited_files, start=1):
        rel_path = file_info.get("file_path", f"File #{i}")
        file_summary = file_info.get("summary", "")
        sec_report = file_info.get("security_report", "No security data.")
        perf_report = file_info.get("performance_report", "No performance data.")
        rating = _extract_rating(sec_report)

        badge = "🟢 SAFE"
        if rating == "CRITICAL":
            badge = "🔴 CRITICAL"
        elif rating == "WARNING":
            badge = "🟡 WARNING"

        lines.extend([
            f"### {i}. `{rel_path}` — Status: {badge}",
            f"",
        ])

        if file_summary:
            lines.append(f"**Role/Summary:** {file_summary}\n")

        lines.extend([
            f"#### 🔒 Security Analysis",
            f"",
            sec_report.strip(),
            f"",
            f"#### ⚡ Performance Analysis & Algorithmic Complexity",
            f"",
            perf_report.strip(),
            f"",
            f"---",
            f"",
        ])

    lines.extend([
        f"## 🛠️ Recommended Action Plan",
        f"",
        f"1. **Triage Critical Vulnerabilities First**: Address all files tagged with 🔴 **CRITICAL** immediately before deploying to staging or production.",
        f"2. **Apply Verified Remediations**: Copy and verify the copy-pasteable remediation blocks generated by the Joint Reconciler Agent.",
        f"3. **CI/CD Integration**: Export SARIF reports and import them directly into GitHub Security alerts using `codeaudit export --sarif`.",
        f"4. **Re-Audit on Commit**: Leverage the SQLite caching engine to re-audit only files that change in future pull requests.",
        f"",
        f"---",
        f"*Report compiled autonomously by [CodeAuditAI](https://github.com/CodeAuditAI)*",
    ])

    return "\n".join(lines)
